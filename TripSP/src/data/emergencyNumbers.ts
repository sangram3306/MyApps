/**
 * Resolves the emergency info for a given search query (country name, trip name, or city).
 */
export function getEmergencyInfoForTrip(tripName?: string, destinationHint?: string): EmergencyContact {
  const query = `${tripName || ''} ${destinationHint || ''}`.toLowerCase();

  const found = EMERGENCY_NUMBERS.find((item) => {
    const cName = item.country.toLowerCase();
    const cCode = item.countryCode.toLowerCase();
    return query.includes(cName) || query.includes(cCode);
  });

  return found || DEFAULT_INTERNATIONAL_EMERGENCY;
}
